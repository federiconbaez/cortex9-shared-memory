"""Puertos del dominio (interfaces). Los adaptadores los implementan."""
from __future__ import annotations

from collections.abc import Callable, Iterable
from typing import Any, Protocol

from .models import (
    Agent,
    Archetype,
    Instrument,
    MemoryFact,
    MessageSummary,
    Relation,
    Session,
    Skill,
)


class Clock(Protocol):
    def now(self) -> str: ...


class MemoryRepository(Protocol):
    # esquema
    def migrate(self) -> list[str]: ...
    def doctor(self) -> list[str]: ...
    def stats(self) -> dict[str, int]: ...
    # agentes / sesiones
    def ensure_agent(self, agent: Agent) -> int: ...
    def agent_id(self, name: str | None) -> int | None: ...
    def add_session(self, s: Session) -> int: ...
    def add_summary(self, m: MessageSummary) -> int: ...
    def recent_summaries(self, agent: str | None = None, limit: int = 5) -> list[dict[str, Any]]: ...
    # codebook (F02)
    def add_alias(self, name: str, expansion: str, agent: str | None) -> None: ...
    def list_aliases(self) -> list[tuple[str, str]]: ...
    # hechos
    def add_fact(self, f: MemoryFact) -> int: ...
    def search_facts(
        self,
        query: str | None,
        type_: str | None,
        include_expired: bool,
        limit: int,
        as_of: str | None = None,
        touch: bool = False,
        half_life_days: float = 30.0,
    ) -> list[dict[str, Any]]: ...
    def supersede_fact(self, old_id: int, new_id: int) -> None: ...
    def touch_facts(self, fact_ids: list[int]) -> None: ...
    def log_label(
        self, label: str, entity_type: str, entity_id: int, context: str, agent: str | None
    ) -> None: ...
    # conocimiento
    def upsert_archetype(self, a: Archetype) -> int: ...
    def list_archetypes(self) -> list[dict[str, Any]]: ...
    def upsert_instrument(self, i: Instrument) -> int: ...
    def list_instruments(self, workstream: str | None) -> list[dict[str, Any]]: ...
    def upsert_skill(self, s: Skill) -> int: ...
    def find_id(self, entity_type: str, key: str) -> int | None: ...
    def exists(self, entity_type: str, entity_id: int) -> bool: ...
    def link_skill(self, skill_id: int, entity_type: str, entity_id: int, note: str) -> int: ...
    def add_relation(self, r: Relation) -> int: ...
    def invalidate_relation(self, relation_id: int, valid_until: str | None = None) -> None: ...
    def neighbors(
        self,
        entity_type: str,
        entity_id: int,
        as_of: str | None = None,
        include_expired: bool = False,
    ) -> list[dict[str, Any]]: ...
    # portabilidad / snapshot
    def export_all(self) -> dict[str, list[dict[str, Any]]]: ...
    def import_all(self, data: dict[str, Iterable[dict[str, Any]]], mode: str) -> dict[str, int]: ...
    def backup_to(self, dest_path: str) -> tuple[str, str]: ...


class CapsuleStore(Protocol):
    """Almacén de cápsulas. `write` es atómico y hace CAS sobre el texto esperado."""

    def read(self, task_id: str) -> str | None: ...
    def write(self, task_id: str, text: str, expected: str | None) -> None: ...
    def list_ids(self) -> list[str]: ...


class FileHasher(Protocol):
    def sha256(self, path: str) -> str | None: ...


class AppendLog(Protocol):
    """Log JSONL append-only. `append_atomic` recibe el texto actual bajo lock y devuelve lo que se agrega."""

    def read_text(self) -> str: ...
    def append_atomic(self, build: Callable[[str], str]) -> str: ...
    def truncate_to(self, size: int) -> None: ...


class LeaseStore(Protocol):
    """Celda única con lock exclusivo. `update` pasa el contenido actual a `fn` y escribe lo que devuelve
    (None = borrar; mismo texto = sin cambio). Devuelve el contenido previo."""

    def read(self) -> str | None: ...
    def update(self, fn: Callable[[str | None], str | None]) -> str | None: ...


class CacheStore(Protocol):
    """Cache por clave: metadatos JSON + contenido, escritura atómica."""

    def read(self, key: str) -> tuple[str | None, str | None]: ...
    def write(self, key: str, meta: str, content: str) -> None: ...
